import { expect, test } from '@playwright/test'

test.skip(process.env.TEXT_MEMORY_LIVE !== '1', 'requires identified disposable text-memory services')

test('自由文本：聊天保存、管理编辑、Unicode超限、整理预览与整批确认', async ({ page, request }) => {
  const api = process.env.TEXT_API_URL!
  const identity = await (await request.get(`${api}/api/v1/_text_identity`)).json()
  expect(identity).toEqual({ id: 'text-20261104-a', database: 'text_browser', model: 'scripted' })
  const email = `text-${Date.now()}@browser.example.test`
  const auth = await (await request.post(`${api}/api/v1/auth/register`, { data: { email, password: 'text-browser-password-2026' } })).json()
  const token = auth.access_token
  expect(typeof token).toBe('string')
  const headers = { Authorization: `Bearer ${token}` }
  const course = await (await request.post(`${api}/api/v1/courses`, { headers, data: { name: '自由文本浏览器自制情境' } })).json()
  await request.post(`${api}/api/v1/chat/sessions`, { headers, data: { course_id: course.id } })
  await page.addInitScript(value => localStorage.setItem('studyrag-token', value), token)
  await page.goto('/')
  await expect(page.getByLabel('输入问题')).toBeEnabled()
  await page.getByLabel('输入问题').fill('记住：先讲直觉，再给定义。')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.locator('.memory-receipt')).toContainText('先讲直觉，再给定义。')
  await page.reload()
  await expect(page.locator('.memory-receipt')).toContainText('已记住')
  await page.getByRole('button', { name: '记忆管理', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '长期记忆管理', exact: true })
  await expect(dialog).toContainText('先讲直觉，再给定义。')
  await expect(dialog.getByLabel('类型', { exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: '编辑', exact: true }).click()
  const editor = dialog.getByLabel('正文', { exact: true })
  await editor.fill('数学推导详细，其他回答简短。')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog.getByRole('list')).toContainText('数学推导详细，其他回答简短。')
  await dialog.getByRole('button', { name: '撤销最近操作' }).click()
  await expect(dialog.getByRole('list')).toContainText('先讲直觉，再给定义。')
  await dialog.getByRole('button', { name: '清空编辑并新增' }).click()
  await editor.fill('😀'.repeat(1001))
  await expect(editor).toHaveValue('😀'.repeat(1001))
  await expect(dialog).toContainText('1001 / 1000')
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
  await editor.fill('请保留条件和例外。'.repeat(120))
  const before = await (await request.get(`${api}/api/v1/memory/items?course_id=${course.id}`, { headers })).json()
  await dialog.getByRole('button', { name: '帮助整理为多条' }).click()
  await expect(dialog.getByText('整理预览：确认前不保存', { exact: true })).toBeVisible()
  const pending = await (await request.get(`${api}/api/v1/memory/items?course_id=${course.id}`, { headers })).json()
  expect(pending.items).toHaveLength(before.items.length)
  await dialog.getByRole('button', { name: '确认并整批保存' }).click()
  await expect(dialog.getByRole('list')).toContainText('数学推导详细，其他简短。')
  await expect(dialog.getByRole('list')).toContainText('先给直觉，再给定义。')
  await dialog.getByRole('button', { name: '关闭长期记忆管理', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: '记忆管理', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('list')).toContainText('数学推导详细，其他简短。')
  await page.getByRole('button', { name: '关闭长期记忆管理', exact: true }).click()
  const send = async (content: string) => {
    await page.getByLabel('输入问题').fill(content)
    await page.getByLabel('输入问题').press('Enter')
    await expect(page.getByLabel('输入问题')).toBeEnabled()
  }
  for (let i = 0; i < 5; i++) await send('这次请一步一步讲解。')
  const card = page.getByLabel('长期记忆建议')
  await expect(card).toBeVisible()
  const beforeAccept = await (await request.get(`${api}/api/v1/memory/items?course_id=${course.id}`, { headers })).json()
  expect(beforeAccept.items).toHaveLength(3)
  await card.getByLabel('候选正文', { exact: true }).fill('以后结合课程实验解释概念。')
  await card.getByRole('button', { name: '保存', exact: true }).click()
  await expect(card).toHaveCount(0)
  const afterAccept = await (await request.get(`${api}/api/v1/memory/items?course_id=${course.id}`, { headers })).json()
  expect(afterAccept.items.some((item: {content: string}) => item.content === '以后结合课程实验解释概念。')).toBe(true)
  for (let i = 0; i < 6; i++) await send('这次请用生活例子讲解。')
  await expect(card).toBeVisible()
  await card.getByRole('button', { name: '不再建议类似内容' }).click()
  await expect(card).toHaveCount(0)
  await page.getByRole('button', { name: '记忆管理', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('已关闭类似建议')
  await page.getByRole('button', { name: '重新允许这些建议' }).click()
  await expect(page.getByRole('dialog')).not.toContainText('已关闭类似建议')
  await request.post(`${api}/api/v1/memory/items`, { headers, data: { content: '默认回答简短。', course_id: course.id, use_mode: 'always', request_key: crypto.randomUUID() } })
  await page.getByRole('button', { name: '关闭长期记忆管理', exact: true }).click()
  for (let i = 0; i < 6; i++) await send('这次请逐行展开。')
  await expect(card).toContainText('将替换原记忆')
  await expect(card).toContainText('默认回答简短。')
  await card.getByLabel('候选正文', { exact: true }).fill('本课程学习目标是通过期末考试。')
  await expect(card.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
  await card.getByLabel('确认用修改后的内容替换上述原记忆').check()
  await card.getByRole('button', { name: '保存', exact: true }).click()
  await expect(card).toHaveCount(0)
  const replaced = await (await request.get(`${api}/api/v1/memory/items?course_id=${course.id}`, { headers })).json()
  expect(replaced.items.some((item: {content: string}) => item.content === '本课程学习目标是通过期末考试。')).toBe(true)
  expect(replaced.items.some((item: {content: string}) => item.content === '默认回答简短。')).toBe(false)
})
