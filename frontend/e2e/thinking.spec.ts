import { newConversation, selectedConversation, selectConversation } from './workspace-actions'
import { expect, test, type Page } from '@playwright/test'
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

// Explicit opt-in: credentials belong only to the isolated acceptance run.
const ctxPath = process.env.THINKING_CONTEXT
test.skip(!ctxPath, 'Set THINKING_CONTEXT to an isolated acceptance context before cleanup.')

test('真实浏览器：开关、发送快照、刷新、账号隔离与停止', async ({ page }) => {
  const ctx = JSON.parse(readFileSync(resolve(ctxPath!), 'utf8'))
  const evidence = resolve(ctx.output, `browser-${Date.now()}`)
  mkdirSync(evidence, { recursive: true })
  const calls: unknown[] = []
  page.on('request', req => {
    if (req.method() === 'POST' && /\/messages$/.test(req.url())) {
      // Only this test's public request selection, no credentials or image bodies.
      const body = req.postDataJSON()
      calls.push({ thinking: body.thinking, content: body.content, attachments: body.attachment_ids.length })
    }
  })
  async function login(p: Page, email: string) {
    await p.getByLabel('邮箱').fill(email)
    await p.getByLabel('密码').fill('thinking-local-only')
    await p.getByRole('button', { name: '进入学习空间' }).click()
    await p.getByRole('button', { name: '退出', exact: true }).waitFor()
  }
  await page.goto('/')
  await login(page, ctx.email)
  await page.getByRole('button', { name: '思考模式增补隔离验收', exact: true }).click()
  const toggle = page.getByRole('button', { name: '深度思考', exact: true })
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await expect(toggle).toHaveCSS('background-color', 'rgb(241, 245, 249)')
  await expect(page.getByText('适合复杂推导、错题分析和多步问题，回答可能需要更长时间。')).toHaveCount(0)
  await toggle.focus()
  await page.keyboard.press('Space')
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await expect(toggle).toHaveClass(/active/)
  await expect(toggle).toHaveCSS('background-color', 'rgb(23, 78, 171)')
  await page.reload()
  await page.getByRole('button', { name: '思考模式增补隔离验收', exact: true }).click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await newConversation(page)
  const q = page.getByLabel('输入问题')
  await expect(q).toBeEnabled()
  await q.fill('不用检索，28+35是多少？简短回答。')
  const response = page.waitForResponse(r => r.request().method() === 'POST' && /\/messages$/.test(r.url()))
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(toggle).toBeDisabled()
  await page.screenshot({ path: resolve(evidence, 'generating.png'), fullPage: true })
  await response
  await expect(q).toBeEnabled({ timeout: 90_000 })
  await expect(page.locator('.chat-message.assistant').last()).toContainText('63')
  await expect(page.locator('.chat-message.assistant').last()).toContainText('深度思考已开启')
  const selected = await selectedConversation(page)
  await page.reload()
  await page.getByRole('button', { name: '思考模式增补隔离验收', exact: true }).click()
  await selectConversation(page, selected)
  await expect(page.locator('.chat-message.assistant').last()).toContainText('63')
  await toggle.click()
  await q.fill('继续刚才的计算结果，减去8。')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(q).toBeEnabled({ timeout: 90_000 })
  await expect(page.locator('.chat-message.assistant').last()).toContainText('55')
  await expect(page.locator('.chat-message.assistant').last()).toContainText('深度思考已关闭')
  // Leave account1 ON; account2 must still start OFF in the same localStorage.
  await toggle.click()
  await page.screenshot({ path: resolve(evidence, 'history.png'), fullPage: true })
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await login(page, 'other-' + ctx.email)
  await page.getByRole('button', { name: '另一账号验收', exact: true }).click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await login(page, ctx.email)
  await page.getByRole('button', { name: '思考模式增补隔离验收', exact: true }).click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  // A genuinely running request is cancelled; DB/SSE public state must agree.
  await q.fill('不用检索，详细推导从1到99中选10个互不相邻整数的组合数公式并解释每一步。')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(toggle).toBeDisabled()
  await page.getByRole('button', { name: '停止', exact: true }).click()
  await expect(q).toBeEnabled()
  await expect(page.locator('.chat-message.assistant').last()).toContainText('已停止')
  await page.screenshot({ path: resolve(evidence, 'cancelled.png'), fullPage: true })
  writeFileSync(resolve(evidence, 'requests.json'), JSON.stringify({ browser: 'local Chrome via Playwright', requests: calls, checks: ['default-off', 'keyboard-on', 'highlight', 'refresh-preference', 'generation-lock', 'snapshot-on', 'history-refresh', 'snapshot-off', 'account-isolation', 'cancel'] }, null, 2))
  expect(calls[0]).toMatchObject({ thinking: true })
  expect(calls[1]).toMatchObject({ thinking: false })
})

test('真实浏览器：刷新后的工具追问、旧消息和图文上下文', async ({ page }) => {
  const ctx = JSON.parse(readFileSync(resolve(ctxPath!), 'utf8'))
  const evidence = resolve(ctx.output, `browser-context-${Date.now()}`)
  mkdirSync(evidence, { recursive: true })
  await page.goto('/')
  await page.getByLabel('邮箱').fill(ctx.email)
  await page.getByLabel('密码').fill('thinking-local-only')
  await page.getByRole('button', { name: '进入学习空间' }).click()
  await page.getByRole('button', { name: '思考模式增补隔离验收', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: '思考模式增补隔离验收', exact: true }).click()
  await selectConversation(page, ctx.browser_session)
  const toggle = page.getByRole('button', { name: '深度思考', exact: true })
  if (await toggle.getAttribute('aria-pressed') !== 'true') await toggle.click()
  const q = page.getByLabel('输入问题')
  await q.fill('严格根据课程资料，重新检索ALPHA冷却时间，引用。')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(q).toBeEnabled({ timeout: 90_000 })
  const answer = page.locator('.chat-message.assistant').last()
  await expect(answer).toContainText('9')
  await expect(answer.locator('.source-card')).toHaveCount(1)
  await selectConversation(page, ctx.legacy_session)
  await expect(page.getByText('思考模式未记录（旧版本）').first()).toBeVisible()
  await page.screenshot({ path: resolve(evidence, 'legacy-and-citations.png'), fullPage: true })
  await newConversation(page)
  await expect(q).toBeEnabled()
  await page.getByLabel('附上题目图片').setInputFiles(resolve('../docs/stage4_thinking/fixtures_final/equation.png'))
  await expect(q).toBeEnabled()
  await q.fill('请讲解图片里的题目，允许通用知识，不需检索。')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(toggle).toBeDisabled()
  await expect(q).toBeEnabled({ timeout: 90_000 })
  await expect(answer).toContainText('7')
  await expect(answer).toContainText('深度思考已开启')
  const sid = await selectedConversation(page)
  await page.reload()
  await page.getByRole('button', { name: '思考模式增补隔离验收', exact: true }).click()
  await selectConversation(page, sid)
  await expect(page.locator('.chat-message.user img')).toBeVisible()
  await q.fill('把刚才得到的x代回上一张图的原方程，左边等于多少？')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(q).toBeEnabled({ timeout: 90_000 })
  await expect(answer).toContainText('44')
  await page.screenshot({ path: resolve(evidence, 'image-followup.png'), fullPage: true })
  writeFileSync(resolve(evidence, 'checks.json'), JSON.stringify({ checks: ['refresh-then-real-rag', 'clickable-citation', 'legacy-unknown', 'image-thinking-on', 'image-refresh-restored', 'image-followup'] }, null, 2))
})
